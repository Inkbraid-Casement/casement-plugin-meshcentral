/// COM for the test's thread, as the plugin's relay thread has it.
struct Com {
    Com() { CoInitializeEx(nullptr, COINIT_MULTITHREADED); }
    ~Com() { CoUninitialize(); }
};

std::uint32_t rgb_at(const Image& image, std::uint32_t x, std::uint32_t y) {
    const std::uint8_t* p = &image.pixels[(std::size_t{y} * image.width + x) * 4];
    return std::uint32_t{p[2]} << 16 | std::uint32_t{p[1]} << 8 | p[0];
}

bool close_to(std::uint32_t a, std::uint32_t b, int tolerance) {
    for (int shift : {0, 8, 16}) {
        int d = static_cast<int>((a >> shift) & 0xFF) - static_cast<int>((b >> shift) & 0xFF);
        if (std::abs(d) > tolerance) return false;
    }
    return true;
}

